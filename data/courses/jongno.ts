/**
 * 종로구 17개 행정동.
 *
 * **읍면동 층의 시험대다.** 지금까지 코스는 전부 시도 아니면 시군구였고,
 * 그 아래로 내려가면 게임이 성립하는지가 확인된 적이 없다.
 *
 * 성립할 이유가 있어서 종로구를 골랐다. 본편은 지도만 보고 이름을 떠올리는
 * 것인데, 동 단위에서 그게 되려면 **모양에 기억이 걸려 있어야** 한다. 종로구는
 * 북쪽이 산(평창·부암), 가운데가 옛 도심(삼청·가회·종로가), 동쪽이 성 밖
 * (창신·숭인)이라 덩어리마다 성격이 다르다. 서울에 살아 본 사람이라면
 * 이름을 아는 동이 절반은 된다.
 *
 * 반대로 이것이 안 되면 읍면동 층 전체가 안 되는 것이다 — 종로구보다
 * 모양이 덜 읽히는 구가 훨씬 많다.
 *
 * 순서는 서쪽 무악에서 인왕산 자락을 타고 북쪽 평창까지 올라간 뒤,
 * 도심으로 내려와 종로를 따라 동쪽 숭인에서 끝난다.
 *
 * ── 이름에 숫자와 점이 든다 ────────────────────────────────
 *
 * 시도·시군구에서는 이름이 전부 한글 음절이었다. 행정동은 아니다 —
 * 전국 3,559곳 중 **30.6%가 숫자를 품고**(창신1동), 0.8%는 가운뎃점까지
 * 든다(종로1·2·3·4가동). 예외가 아니라 이 층의 성질이다.
 *
 * 숫자는 그대로 둔다. `창신1동`이 그 동네의 이름이고, 숫자는 자판에 있다.
 *
 * **가운뎃점만 표준을 바꾼다.** `·`는 한글 자판에 없어서, 그대로 두면
 * 따라치기와 정답 베껴 쓰기에서 아예 칠 수 없는 문제가 된다 — 지명을 묻는
 * 것이 아니라 특수문자 입력을 묻는 셈이다. 그래서 표준은 `종로1234가동`이고
 * 공식 표기 `종로1·2·3·4가동`이 별칭으로 들어온다. `place.ts`가 세운
 * "지도에 적힌 이름을 그대로 친다"에 대한 유일한 예외이고, 이유는 편의가
 * 아니라 **칠 수 없음**이다. 전국에서 서른 곳이 여기 해당한다.
 *
 * ── 아직 `index.ts`에 등록하지 않았다 ──────────────────────────
 *
 * 지도는 만들어진다. `npm run build:geo`가 이 폴더를 직접 훑으므로 등록과
 * 무관하게 잡히고, 17곳이 경계 17개에 하나도 어긋나지 않고 붙었다.
 *
 * 등록을 미룬 것은 **정복도 셈이 아직 이 층을 모르기 때문**이다.
 *
 *  · `lib/home/summary.ts`의 totalRegions가 겹치지 않는 코스를 전부 더한다.
 *    여기 17을 보태면 첫 화면의 `245`가 `262`가 되는데, 그 245는 "17 시도 +
 *    228 시군구"라고 적혀 있는 수다. 동을 섞으면 무엇을 세는 수인지 사라진다.
 *
 *  · 같은 파일의 byPrefix가 시도 코드로 코스를 하나씩 잡는다. 이 코스의
 *    시도는 `11`이라 서울과 부딪친다 — 첫 화면의 서울 줄이 서울 25구가
 *    아니라 종로구 17동을 가리킬 수 있다.
 *
 * `overlapping`으로 빠져나갈 수는 없다. 그 깃발의 뜻은 "이 지역이 다른
 * 코스에도 들어 있다"이고, 켜면 오답이 원래 속한 코스의 노트로 흩어진다
 * (`lib/score/notebooks.ts`). 동의 오답은 이 코스의 것이라 그러면 안 된다.
 *
 * 그러니 다음 걸음은 코스를 더 만드는 것이 아니라 **층(level) 개념을 세우는
 * 것**이다. 무엇을 정복도에 세고 무엇을 안 셀지가 거기서 갈린다.
 */

