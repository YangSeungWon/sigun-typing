/**
 * 행정구역이 바뀐 **실제 날짜와 그 내용.**
 *
 * 경계 자료에서는 이걸 알 수 없다. 두 가지가 겹친다.
 *
 * **간격.** SGIS 도형이 1975~2000년에는 5년 단위라, 그 사이 어느 날 일어난
 * 일이 다음 판에 처음 나타날 뿐이다 — 대구·인천직할시는 1981년에 생겼는데
 * 자료에서는 1985년 판에서 처음 보인다.
 *
 * **지연.** 1년 단위인 2001년 이후에도 자료가 개편을 곧바로 따라가지 않는다.
 * 제주특별자치도는 2006년 7월 1일 출범인데 2006년 판(기준일 12월 31일)에는
 * 아직 `제주도`로 적혀 있고 2007년 판에서야 바뀐다.
 *
 * 그래서 여기만 **손으로 적는다.** 이 저장소에서 도형에서 유도하지 않고 사람이
 * 적어 넣은 유일한 사실이므로, 틀리면 여기만 고치면 된다.
 *
 * ── 문장이 아니라 짝으로 적는다 ──────────────────────────
 *
 * `무엇이 무엇으로`는 화면에서 표로 읽힌다. 문장으로 적어 두면 그걸 다시
 * 이어 붙여야 하고, 여러 건이 겹치면 가운뎃점으로 늘어놓게 된다.
 * `before → after` 두 칸이면 눈이 세로로 훑는다.
 *
 * ── 다 적지 않았다 ─────────────────────────────────────
 *
 * 확실한 것만 적었다. 없는 해는 화면이 도형에서 뽑은 짝을 쓰고, 그 해는
 * **자료에 처음 나타난 해**로 표시된다 — 실제 시행일보다 늦을 수 있다.
 *
 * 짝은 `boundary-changes.json`의 사건과 `seenAt`(자료에 처음 나타난 해)로 맞춘다.
 */
export interface AdminEvent {
  /** 이 변화가 자료에 처음 나타난 해. boundary-changes.json의 `to`와 같다. */
  seenAt: string;
  dates: AdminDate[];
}

export interface AdminDate {
  /** 시행일. */
  on: string;
  /** 바뀌기 전. 새로 생기기만 한 것은 비운다. */
  from?: string[];
  /** 바뀐 뒤. 없어지기만 한 것은 비운다. */
  to?: string[];
  /**
   * 이 날 생긴 곳과, 그것이 떨어져 나온 도.
   *
   * 한 판에 두 사건이 묶였을 때 **앞 사건의 상태를 만들어 내기 위해** 쓴다.
   * 1990년 판에는 광주(1986)와 대전(1989)이 둘 다 있는데, 대전을 충남으로
   * 도로 합치면 그것이 1986년의 지도다. 없던 것을 그리는 것이 아니라 있는
   * 것을 되돌리는 것이라 도형이 지어내지지 않는다.
   */
  born?: { code: string; parent: string };
  /**
   * 이 날 **경계는 그대로고 이름만** 바뀐 곳. 앞 시점의 코드로 적는다.
   *
   * 승격이 다 경계를 바꾸지는 않는다 — 당진군이 당진시가 된 것은 이름과
   * 지위가 바뀐 것이지 땅이 달라진 게 아니다. 그런 사건은 앞 판의 도형을
   * 그대로 두고 이름만 갈아 끼우면 그 시점의 지도가 된다.
   */
  renames?: { code: string; to: string }[];
}

