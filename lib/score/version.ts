/**
 * 채점 규칙 버전.
 *
 * 기록끼리 비교가 가능하려면 같은 규칙으로 계산돼야 한다. 규칙을 바꾸고도
 * 버전을 그대로 두면 옛 기록과 새 기록이 한 순위표에 섞여 버리고, 그 뒤로는
 * 어느 쪽이 어느 규칙인지 알 방법이 없어 되돌릴 수도 없다.
 *
 * ── 버전을 올려야 하는 변경 ──────────────────────────────────────
 *   · 두벌식 타수 계산(keystrokeCount)이 달라질 때
 *   · 무엇을 오타로 세는지, 정확도의 분모가 달라질 때
 *   · CPM·정확도 공식이 달라질 때
 *   · 초성 힌트 페널티 시간이 달라질 때
 *   · 서버가 elapsed를 산출하는 방식이 달라질 때
 *
 * ── 올릴 필요가 없는 변경 ────────────────────────────────────────
 *   · 안티치트 임계값 조정 (통과/거부만 달라질 뿐 점수는 그대로다)
 *   · UI, 지도, 코스 설명
 *
 * 버전이 다른 기록은 순위표에서 섞이지 않는다. 올린 뒤에는 기존 기록이
 * 보이지 않게 되므로, 정말 비교가 불가능해진 경우에만 올릴 것.
 *
 * ── 이력 ─────────────────────────────────────────────────────────
 *   1  최초. 두벌식 자모 타수, CPM = 정답타수/경과시간, 힌트 +5초.
 *   4  정확도를 제출 기준으로 바꿨다. 예전에는 실제로 누른 타건을 전부 분모에
 *      넣어, 치다가 한 글자 지우고 고친 것이 몰라서 틀린 것과 같은 값으로
 *      찍혔다. 이제 분모는 제출한 타수(맞힌 타수 + 틀리게 낸 타수)이고, 치는
 *      도중의 이탈은 어느 모드에서도 오타로 세지 않는다.
 *   3  초성 힌트 페널티가 5초에서 30초로 올랐다. 5초는 지역 하나를 치는 시간의
 *      두 배 남짓이라, 힌트를 몇 번 봐도 기록이 크게 흔들리지 않았다 — 힌트가
 *      대가가 아니라 값싼 상품이었다. 두 값으로 낸 기록은 나란히 둘 수 없다.
 *   2  회상 모드가 엔터 제출로 바뀌었다. 오답을 제출하면 그때까지의 타수가
 *      정답 타수에서 빠지므로(분모에는 남는다) 같은 실력이라도 정확도가
 *      달라지고, 오타 집계 단위도 "경로 이탈 횟수"에서 "오답 제출 횟수"로
 *      바뀌었다. 두 규칙의 기록은 나란히 둘 수 없다.
 */
